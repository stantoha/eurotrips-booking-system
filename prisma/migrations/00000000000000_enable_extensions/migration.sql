-- =============================================================================
-- Розширення PostgreSQL, потрібні схемі
--
-- Проблема, яку це закриває: усі моделі використовують
-- `@default(dbgenerated("uuid_generate_v4()"))`, але жодна міграція не
-- створювала розширення `uuid-ossp`. На наявних БД воно було заведене
-- вручну, тому `migrate deploy` працював. А `migrate reset` і будь-яке
-- свіже середовище (CI, новий розробник) падали на першій же міграції:
--
--   ERROR: function uuid_generate_v4() does not exist  (42883)
--
-- Назва 00000000000000_ навмисна: міграції застосовуються в лексикографічному
-- порядку імен, тож ця йде перед 20260705101941_add_tour_checklists.
--
-- IF NOT EXISTS робить її безпечною для БД, де розширення вже стоїть:
-- на них вона просто позначиться застосованою і нічого не змінить.
-- Наявні міграції не редагувались — їхні контрольні суми лишились ті самі.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
