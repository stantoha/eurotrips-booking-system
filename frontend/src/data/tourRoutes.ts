/** Нормалізація назви туру для зіставлення з реальними tour.name (може мати іншу дату/сезон у дужках). */
function normalizeName(name: string): string {
  return name
    .toLowerCase()
    .replace(/без нічних/gi, '')
    .replace(/\([^)]*\)/g, '')
    .replace(/[–—-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

const ROUTES_BY_NORMALIZED_NAME = new Map<string, TourRoute>(
  TOUR_ROUTES.map((route) => [normalizeName(route.name), route])
);

/** Шукає маршрут для туру за назвою (з допуском на дати/суфікси в дужках). */
export function findRouteForTour(tourName: string): TourRoute | undefined {
  const normalized = normalizeName(tourName);
  if (ROUTES_BY_NORMALIZED_NAME.has(normalized)) {
    return ROUTES_BY_NORMALIZED_NAME.get(normalized);
  }
  // Часткове співпадіння — тур міг отримати сезонний префікс/суфікс у назві.
  return TOUR_ROUTES.find((route) => {
    const n = normalizeName(route.name);
    return normalized.includes(n) || n.includes(normalized);
  });
}
