/** Пошук координат по назві пункту, з нормалізацією регістру/пробілів. */
export function getCoordinates(placeName: string): LatLng | undefined {
  const key = placeName.trim();
  if (GEO_COORDINATES[key]) return GEO_COORDINATES[key];
  const normalized = key.toLowerCase();
  const found = Object.keys(GEO_COORDINATES).find((k) => k.toLowerCase() === normalized);
  return found ? GEO_COORDINATES[found] : undefined;
}
